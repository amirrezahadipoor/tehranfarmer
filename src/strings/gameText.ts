export const GT: Record<keyof typeof GT_FA, string> = new Proxy(GT_FA as Record<keyof typeof GT_FA, string>, {
  get(_target, prop: string) {
    const k = prop as keyof typeof GT_FA;
    return CFG.locale === 'en' ? (GT_EN[k] ?? GT_FA[k]) : GT_FA[k];
  },
});

const FA_TO_EN = new Map<string, string>();
for (const k of Object.keys(GT_FA) as (keyof typeof GT_FA)[]) FA_TO_EN.set(GT_FA[k], GT_EN[k]);

export function locText(faStr: string): string {
  return CFG.locale === 'en' ? (FA_TO_EN.get(faStr) ?? faStr) : faStr;
}
