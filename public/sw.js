const CACHE_NAME = 'mazrae-rangi-offline-v15';
const CORE_ASSETS = [
  './', './index.html', './manifest.webmanifest', './icon.svg',
  './music/peaceful-forest.mp3', './music/ch2.mp3', './music/ch3.mp3',
  './music/ch4.mp3', './music/ch5.mp3', './music/ch6.mp3', './music/ch7.mp3',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res && res.status === 200 && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(() => caches.match(req).then((hit) => hit || caches.match('./index.html') || caches.match('./'))),
  );
});
